FILL = {'K': ('', '#000'), 'W': ('', '#fff'), 'D': ('d', 'url(#ldp-d)'), 'G': ('g', 'url(#ldp-g)'), 'L': ('l', 'url(#ldp-l)')}
# Patterns in sprite units: one sprite pixel = 4 device pixels, so a 0.25 unit cell is one device pixel.
DEFS = ('<defs>'
        '<pattern id="ldp-d" width="0.5" height="0.5" patternUnits="userSpaceOnUse"><rect width="0.5" height="0.5" fill="#000"/><rect x="0.25" y="0.25" width="0.25" height="0.25" fill="#fff"/></pattern>'
        '<pattern id="ldp-g" width="0.5" height="0.5" patternUnits="userSpaceOnUse"><rect width="0.5" height="0.5" fill="#fff"/><rect width="0.25" height="0.25" fill="#000"/><rect x="0.25" y="0.25" width="0.25" height="0.25" fill="#000"/></pattern>'
        '<pattern id="ldp-l" width="0.5" height="0.5" patternUnits="userSpaceOnUse"><rect width="0.5" height="0.5" fill="#fff"/><rect width="0.25" height="0.25" fill="#000"/></pattern>'
        '</defs>')
def svg(name, art, px=4):
    rows = art.strip('\n').split('\n'); h, w = len(rows), max(len(r) for r in rows); out = []
    for y, r in enumerate(rows):
        for ch, (cls, fill) in FILL.items():
            for m in re.finditer(ch + '+', r):
                c = f' class="{cls}"' if cls else ''
                out.append(f'<rect{c} x="{m.start()}" y="{y}" width="{m.end() - m.start()}" height="1" fill="{fill}"/>')
    kind = name.split('_')[0]
    return f'<svg class="ld-sprite ld-sprite--{kind}" viewBox="0 0 {w} {h}" width="{w * px}" height="{h * px}" shape-rendering="crispEdges">{DEFS}{"".join(out)}</svg>'
block = '{%- comment -%} Sprites (generated by dev/sprites.py, do not edit by hand). {%- endcomment -%}\n'
for k, v in SPRITES.items():
    block += '{%- capture sp_' + k + ' -%}' + svg(k, v) + '{%- endcapture -%}\n'
block += '{%- comment -%} /Sprites {%- endcomment -%}\n'
p = 'src/shared.liquid'; s = open(p).read()
s = re.sub(r'\{%- comment -%\} Sprites \(generated.*?/Sprites \{%- endcomment -%\}\n\n?', '', s, flags=re.S)
anchor = '{%- comment -%} The little adventurer'
i = s.index(anchor)
open(p, 'w').write(s[:i] + block + '\n' + s[i:])
print('sprites:', ', '.join(SPRITES))
